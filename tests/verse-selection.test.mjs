import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {JSDOM} from 'jsdom';

test('verse taps select contiguous passages and double taps study selections and saved highlights',async()=>{
 const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
 const dom=new JSDOM(html,{url:'https://example.test/',runScripts:'outside-only'});
 const {document}=dom.window,context=dom.getInternalVMContext();
 let code=await readFile(new URL('../app.js',import.meta.url),'utf8');
 code=code.replace(/^import .*;\n/gm,'');
 vm.runInContext(code.slice(0,code.lastIndexOf('start().catch')),context);
 vm.runInContext(`
  state.books=[{id:'JHN',name:'John',numberOfChapters:21}];
  state.data={translation:{name:'Berean'},chapter:{content:Array.from({length:8},(_,i)=>({type:'verse',number:i+1,content:['Text '+(i+1)]}))}};
  state.highlights={'JHN.1.6':true,'JHN.1.7':true,'JHN.1.8':true};
  state.tab='notes';
  renderChapter();
 `,context);
 let opens=0;
 document.addEventListener('open-mobile-study',()=>opens++);
 const verse=n=>document.querySelector(`[data-verse="${n}"]`);
 const tap=n=>verse(n).dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true,detail:1}));
 const selected=()=>[...document.querySelectorAll('[data-verse][aria-pressed="true"]')].map(el=>Number(el.dataset.verse));
 tap(2);tap(3);tap(4);
 assert.deepEqual(selected(),[2,3,4]);
 assert.equal(opens,0);
 tap(4);
 assert.equal(opens,1);
 assert.equal(document.getElementById('studyRef').textContent,'John 1:2–4');
 assert.match(document.querySelector('#studyBody blockquote').textContent,/Text 2.*Text 3.*Text 4/);
 assert.equal(document.getElementById('studyFocusVerse'),null);
 const editor=document.getElementById('noteText');
 editor.value='A note for the whole range';
 editor.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
 const saved=JSON.parse(dom.window.localStorage.getItem('exegetical-notes'));
 assert.deepEqual(Object.keys(saved),['JHN.1.2-4']);
 assert.equal(saved['JHN.1.2-4'].endVerse,4);
 document.getElementById('highlightVerse').click();
 assert.deepEqual([2,3,4].map(n=>verse(n).classList.contains('highlighted')),[true,true,true]);
 document.getElementById('highlightVerse').click();
 assert.deepEqual([2,3,4].map(n=>verse(n).classList.contains('highlighted')),[false,false,false]);
 tap(4);
 assert.deepEqual(selected(),[2,3]);
 assert.equal(opens,1);
 vm.runInContext('resetVerseTap()',context);
 tap(4);
 vm.runInContext('resetVerseTap()',context);
 tap(4);
 assert.deepEqual(selected(),[2,3]);
 tap(4);
 assert.deepEqual(selected(),[2,3,4]);
 assert.equal(opens,2);
 assert.equal(document.getElementById('studyRef').textContent,'John 1:2–4');
 tap(7);
 assert.deepEqual(selected(),[7]);
 tap(7);
 assert.deepEqual(selected(),[6,7,8]);
 assert.equal(opens,3);
 assert.equal(document.getElementById('studyRef').textContent,'John 1:6–8');
 tap(1);tap(1);
 assert.deepEqual(selected(),[1]);
 assert.equal(opens,4);
 assert.equal(document.getElementById('studyRef').textContent,'John 1:1');
 tap(1);
 assert.deepEqual(selected(),[]);
 dom.window.close();
});

test('range notes and single-verse records sync independently, including deletions',async()=>{
 const {payloadFor,recordsToState,validatePayload,mergeRemoteStudy}=await import('../sync-model.js');
 const single='JHN.1.2',range='JHN.1.2-4';
 const base={book:'JHN',bookName:'John',chapter:1,verse:2};
 const notes={[single]:{...base,text:'Verse note'},[range]:{...base,text:'Range note',endVerse:4}};
 const rows=[single,range].map(passage=>({passage,payload:payloadFor(passage,notes,{[single]:true}),revision:1}));
 assert.deepEqual(recordsToState(rows).highlights,{[single]:true});
 assert.equal(recordsToState(rows).notes[range].text,'Range note');
 assert.equal(validatePayload(range,{...rows[1].payload,endVerse:5}),false);
 const state=recordsToState(rows);
 const deleted={passage:range,payload:payloadFor(range,{},{}),revision:2};
 assert.equal(mergeRemoteStudy([deleted],{...state,revisions:new Map(),pending:new Map(),editingKey:null}),true);
 assert.equal(state.notes[range],undefined);
 assert.equal(state.notes[single].text,'Verse note');
});
